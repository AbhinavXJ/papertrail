// Copies runtime assets for PDF reading and OCR into public/vendor so the app
// serves them from its own origin. Nothing is ever loaded from a CDN.
//   public/vendor/pdfjs/      pdf.js worker, CMaps, standard fonts, wasm decoders
//   public/vendor/tesseract/  Tesseract.js worker, LSTM wasm cores, English model
import { copyFileSync, cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const root = process.cwd();
const pkgDir = (name) => dirname(require.resolve(`${name}/package.json`, { paths: [root] }));

function copy(from, to) {
  if (!existsSync(from)) throw new Error(`[copy-vendor] missing ${from}`);
  mkdirSync(dirname(to), { recursive: true });
  copyFileSync(from, to);
}

const out = join(root, "public", "vendor");
rmSync(out, { recursive: true, force: true });

// pdf.js
const pdfjs = pkgDir("pdfjs-dist");
const pdfOut = join(out, "pdfjs");
copy(join(pdfjs, "build", "pdf.worker.min.mjs"), join(pdfOut, "pdf.worker.min.mjs"));
for (const dir of ["cmaps", "standard_fonts", "iccs"]) {
  if (existsSync(join(pdfjs, dir))) cpSync(join(pdfjs, dir), join(pdfOut, dir), { recursive: true });
}
for (const f of ["jbig2.wasm", "openjpeg.wasm", "qcms_bg.wasm", "jbig2_nowasm_fallback.js", "openjpeg_nowasm_fallback.js"]) {
  const p = join(pdfjs, "wasm", f);
  if (existsSync(p)) copy(p, join(pdfOut, "wasm", f));
}

// Tesseract.js (LSTM-only builds; the worker picks the variant matching the device's SIMD support)
const tess = pkgDir("tesseract.js");
const core = dirname(require.resolve("tesseract.js-core/package.json", { paths: [tess] }));
const eng = pkgDir("@tesseract.js-data/eng");
const tOut = join(out, "tesseract");
copy(join(tess, "dist", "worker.min.js"), join(tOut, "worker.min.js"));
for (const v of ["lstm", "simd-lstm", "relaxedsimd-lstm"]) {
  copy(join(core, `tesseract-core-${v}.wasm.js`), join(tOut, "core", `tesseract-core-${v}.wasm.js`));
}
copy(join(eng, "4.0.0_best_int", "eng.traineddata.gz"), join(tOut, "lang", "eng.traineddata.gz"));

writeFileSync(join(out, "README.txt"), "Generated by scripts/copy-vendor.mjs. Do not edit or commit.\n");
console.log("[copy-vendor] pdf.js and Tesseract assets -> public/vendor/");
